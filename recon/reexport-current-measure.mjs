// Usage: node recon/reexport-current-measure.mjs <label> <absolute pinned root>
import { parseProject, buildGraph, calculateHealthScore } from '../dist/sdk.js';
import { execFileSync } from 'node:child_process';

const [repo, root] = process.argv.slice(2);
if (!repo || !root) throw new Error('Expected repo label and absolute root');
const category = path => {
  const x = path.toLowerCase().replaceAll('\\', '/');
  const segments = x.split('/');
  const has = (...names) => segments.some(segment => names.includes(segment));
  if (has('generated', '__generated__', 'autogenerated', 'autogen', 'dist', 'build') || /\.generated\.[^.]+$/.test(x)) return 'generated';
  if (has('bench', 'benches', 'benchmark', 'benchmarks') || /\.bench\.[cm]?[jt]sx?$/.test(x)) return 'benchmark';
  if (has('fixture', 'fixtures', '__fixtures__', 'testdata', 'test-data')) return 'fixture';
  if (has('test', 'tests', '__tests__', 'testing', 'e2e', 'integration-tests', 'integration_test')
    || /(?:^|\/)test_[^/]+\.py$|_test\.py$|\.(?:test|spec)\.[cm]?[jt]sx?$/.test(x)) return 'test';
  if (has('sample', 'samples', 'example', 'examples', 'demo', 'demos', 'playground')) return 'example';
  return 'production';
};
const files = await parseProject(root, { useCache: false });
const graph = buildGraph(files, root);
const pairs = new Set();
const edgeKinds = {};
graph.forEachEdge((_id, attrs, source, target) => {
  edgeKinds[attrs.kind] = (edgeKinds[attrs.kind] ?? 0) + 1;
  if (attrs.kind === 'references-type') return;
  const from = graph.getNodeAttribute(source, 'filePath');
  const to = graph.getNodeAttribute(target, 'filePath');
  if (from !== to && category(from) === 'production' && category(to) === 'production') pairs.add(`${from}\0${to}`);
});
const sites = graph.getAttribute('reExportSites') ?? [];
const siteCounts = {};
for (const site of sites) siteCounts[site.classification] = (siteCounts[site.classification] ?? 0) + 1;
const health = calculateHealthScore(graph, root);
console.log(JSON.stringify({ repo, sha: execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(),
  parsedFiles: files.length, symbols: files.reduce((count, file) => count + file.symbols.length, 0),
  builtEdges: edgeKinds, productionPairs: pairs.size, overall: health.overall,
  dimensions: health.dimensions.map(dimension => ({ name: dimension.name, score: dimension.score, metrics: dimension.metrics })),
  reExportSites: siteCounts, reconciliation: {
    parsed: graph.getAttribute('parserEdgeCount'), built: graph.getAttribute('parserBuiltEdgeCount'),
    drops: graph.getAttribute('edgeDrops').length,
    crossLanguage: graph.getAttribute('crossLanguageAttemptedEdgeCount') } }));
