// Diagnostic only: measure the proposed production relationship view.
// Usage: node recon/coupling-refit-measure.mjs <label> <absolute repo root>
import { parseProject, buildGraph } from '../dist/sdk.js';
import { execFileSync } from 'node:child_process';

const [label, root] = process.argv.slice(2);
if (!label || !root) throw new Error('Usage: node recon/coupling-refit-measure.mjs <label> <absolute repo root>');

function category(path) {
  const x = path.toLowerCase().replaceAll('\\', '/');
  const segments = x.split('/');
  const has = (...names) => segments.some(s => names.includes(s));
  if (has('generated', '__generated__', 'autogenerated', 'autogen', 'dist', 'build') || /\.generated\.[^.]+$/.test(x)) return 'generated';
  if (has('bench', 'benches', 'benchmark', 'benchmarks') || /\.bench\.[cm]?[jt]sx?$/.test(x)) return 'benchmark';
  if (has('fixture', 'fixtures', '__fixtures__', 'testdata', 'test-data')) return 'fixture';
  if (has('test', 'tests', '__tests__', 'testing', 'e2e', 'integration-tests', 'integration_test')
    || /(?:^|\/)test_[^/]+\.py$|_test\.py$|\.(?:test|spec)\.[cm]?[jt]sx?$/.test(x)) return 'test';
  if (has('sample', 'samples', 'example', 'examples', 'demo', 'demos', 'playground')) return 'example';
  return 'production';
}

const files = await parseProject(root, { useCache: false });
const graph = buildGraph(files, root);
const graphFiles = new Set();
graph.forEachNode((_id, attrs) => graphFiles.add(attrs.filePath));
const production = new Set([...graphFiles].filter(path => category(path) === 'production'));
const pairs = new Set();
const allPairs = new Set();
const volume = { production: 0, excluded: 0, all: 0 };
const excluded = {};
graph.forEachEdge((_edge, attrs, source, target) => {
  if (attrs.kind === 'references-type') return;
  const from = graph.getNodeAttribute(source, 'filePath');
  const to = graph.getNodeAttribute(target, 'filePath');
  if (from === to) return;
  volume.all++;
  allPairs.add(`${from}\0${to}`);
  if (production.has(from) && production.has(to)) {
    volume.production++;
    pairs.add(`${from}\0${to}`);
  } else {
    volume.excluded++;
    const key = `${category(from)}→${category(to)}`;
    excluded[key] = (excluded[key] ?? 0) + 1;
  }
});
const outward = new Map([...production].map(file => [file, new Set()]));
for (const pair of pairs) {
  const [from, to] = pair.split('\0');
  outward.get(from).add(to);
}
const degrees = [...outward.values()].map(targets => targets.size).sort((a, b) => a - b);
const p95 = degrees.length ? degrees[Math.ceil(.95 * degrees.length) - 1] : null;
const max = degrees.length ? degrees.at(-1) : null;
const mean = degrees.length ? pairs.size / degrees.length : null;
const sha = execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
console.log(JSON.stringify({ label, sha, parsedFiles: files.length, graphFiles: graphFiles.size,
  productionFiles: production.size, allPairs: allPairs.size, productionPairs: pairs.size,
  meanOut: mean, p95Out: p95, maxOut: max, volume, excluded,
  coverage: label === 'drizzle' || label === 'hono' ? 'known-ts-side-effect-gap'
    : label === 'flask' || label === 'fastapi' || label === 'werkzeug' ? 'python-absolute-unverified'
      : 'construct-bounded' }));
